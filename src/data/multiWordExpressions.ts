// PRECOMPUTED CONTEXT-AWARE MULTI-WORD EXPRESSION (MWE) DICTIONARY
// Recognizes phrasal verbs, idioms, fixed expressions, and meaningful academic collocations
// as single semantic units with grammatical inflection, separable-verb handling, and contextual sense disambiguation.
// Zero runtime API calls or external network requests.

export type MultiWordExpressionCategory =
  | 'Phrasal verb'
  | 'Idiom'
  | 'Fixed expression'
  | 'Academic collocation'
  | 'Compound expression';

export interface MultiWordExpressionSense {
  id: string;
  def: string;
  ctx: string;
  ex: string;
  /** Context cue words in the surrounding sentence/paragraph that signal this sense */
  keywords: string[];
  /** Optional cue words appearing specifically in the direct object / right-hand window of the expression */
  rightWindowCues?: string[];
  /** If true, this sense is preferred when the expression is used intransitively (followed by punctuation, end of clause, or adverb) */
  preferWhenIntransitive?: boolean;
  /** Optional lesson IDs where this sense is known to appear */
  lessonIds?: string[];
}

export interface MultiWordExpressionEntry {
  /** Canonical dictionary form (e.g., "back up", "give up", "take into account") */
  canonical: string;
  /** Display category shown in the vocabulary popup (e.g., "Phrasal verb", "Idiom") */
  category: MultiWordExpressionCategory;
  /**
   * Pattern tokens in lowercase.
   * Special wildcards supported:
   * - `<head>` or index specified by `headWordIndex`: matches the canonical token AND its morphological inflections (e.g., back/backs/backed/backing, give/gives/gave/given/giving).
   * - `*MOD*`: optional single-word intensifier/modifier (e.g., "key", "vital", "major", "important", "crucial", "significant", "central", "close", "direct", "active", "critical").
   */
  tokens: string[];
  /** Index of the inflectable head word (usually 0 for verb phrases like "carry out" or "play a role in") */
  headWordIndex?: number;
  /** Explicit irregular or additional inflected forms for the head token */
  headInflections?: string[];
  /**
   * Whether the head verb and particle/complement can be separated by an object pronoun or short noun phrase
   * (e.g., "back it up", "back the files up", "turn the offer down", "take the local climate into account").
   * Value indicates the index of the particle/continuation token after the gap (typically 1).
   */
  separableAtIndex?: number;
  /** Maximum number of intervening object tokens allowed when separated (default 3) */
  maxSeparableTokens?: number;
  /** Words immediately preceding the match that indicate a literal spatial combination rather than this expression (e.g., "walked back up") */
  negativeLeftCues?: string[];
  /** Words immediately following the match that indicate a literal spatial combination rather than this expression (e.g., "turned down the street") */
  negativeRightCues?: string[];
  /** Default simple English definition */
  def: string;
  /** Default contextual meaning explanation */
  ctx: string;
  /** Example sentence */
  ex: string;
  /** Optional synonyms */
  syn?: string[];
  /** Context-disambiguated senses for polysemous expressions */
  senses?: MultiWordExpressionSense[];
}

